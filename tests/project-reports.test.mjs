import assert from 'node:assert/strict';
import * as c from '../core.js';
const row = {id:'sample:project',name:'sample: Pumps',status:'won',value:900,client:'sample: Client',threads:[]};
const at = '2026-11-13T22:00:00Z';
assert.equal(typeof c.projectWorkUpdate,'function','project follow-up model is implemented');
let data = c.projectWorkUpdate(null,row,{owner:'sample: Owner',action:'Review delivery',actionDue:'2026-11-15',execution:'ongoing',award:800,collected:200,milestones:[{id:'a',title:'Supply',weight:60,done:true},{id:'b',title:'Install',weight:40,done:false}]},{at,id:'sample:e1'});
assert.equal(c.projectProgress(c.projectWorkFind(data,row)),60);
assert.equal(c.projectWorkFind(data,row).history.length,1);
assert.throws(()=>c.projectWorkUpdate(data,row,{execution:'delivered'},{at,id:'sample:e2'}),/milestones/);
assert.throws(()=>c.projectWorkUpdate(null,{...row,status:'submitted'},{execution:'ongoing'},{at,id:'sample:e3'}),/award/);
assert.throws(()=>c.projectWorkUpdate(data,row,{collected:-1},{at,id:'sample:e4'}),/money/);
assert.throws(()=>c.projectWorkUpdate(data,row,{actionDue:'2026-02-30'},{at,id:'sample:e5'}),/date/);
const linked = {...row,tender:'sample:tender'};
data=c.projectWorkUpdate(data,linked,{risk:'Awaiting access'},{at,id:'sample:e6'});
assert.equal(c.projectWorkFind(data,{...linked,id:'sample:new-row'}).owner,'sample: Owner','explicit reference survives row identity changes');
const report=c.projectReport([linked,{...row,id:'sample:other',name:'sample: Other',client:'Other'}],data,{client:'sample: Client',from:'2026-11-14',to:'2026-11-14'},'2026-11-16');
assert.equal(report.rows.length,1);assert.equal(report.events.length,2,'event window uses Saudi day');
assert.equal(report.totals.offer,900);assert.equal(report.totals.award,800);assert.equal(report.totals.collected,200);assert.equal(report.totals.overdue,1);
assert.equal(c.projectReport([linked],data,{from:'2026-11-15',to:'2026-11-15'},'2026-11-16').events.length,0);
assert.throws(()=>c.projectReport([row],data,{from:'2026-11-16',to:'2026-11-15'}),/date/);
const older=structuredClone(data);
data=c.projectWorkUpdate(data,linked,{owner:'sample: New owner'},{at:'2026-11-15T09:00:00Z',id:'sample:e7'});
const merged=c.mergeProjectWork(data,older);
assert.equal(c.projectWorkFind(merged,linked).owner,'sample: New owner');
assert.equal(c.projectWorkFind(merged,linked).history.length,3);
assert.equal(c.projectWorkFind(c.mergeProjectWork(null,data),linked).owner,'sample: New owner');
assert.equal(c.projectReport([row],null).totals.award,0);assert.equal(c.projectReport([row],null).totals.awardMissing,1,'unknown award is not inferred from offer');
assert.equal(c.projectProgress({milestones:[]}),null);
const mailRow={id:'m:sample: mail',name:'sample: Mail',status:'worked',threads:[{project:'sample: Mail'}]};
const mailWork=c.projectWorkUpdate(null,mailRow,{owner:'sample: Mail owner'},{at,id:'sample:mail-event'});
assert.equal(c.projectWorkFind(mailWork,{...mailRow,id:'i:sample:converted'}).owner,'sample: Mail owner','mail-to-register conversion retains follow-up through explicit thread references');
assert.equal(c.projectReport([linked],data,{owner:'nobody'}).rows.length,0);
assert.equal(c.projectReport([{...row,status:'lost'}],data).rows[0].status,'lost','execution never overwrites a lost tender');
assert.equal(c.projectWorkFind(c.cleanProjectWork(JSON.parse(JSON.stringify(data))),linked).history.length,3);
console.log('project-reports.test.mjs: lifecycle, identity, values, filters, Saudi dates, restore and validation passed');
