import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { JSDOM } from 'jsdom';
import { DOMMatrix, ImageData, Path2D, createCanvas } from '@napi-rs/canvas';
import { PDFDocument } from 'pdf-lib';
import { zipSync, strToU8 } from '../assets/vendor/fflate.mjs';
import { fixtures, spreadsheetLibrary } from './tender-fixtures.mjs';
import { readTenderDocument } from '../assets/tender-documents.js';
Object.assign(globalThis,{DOMMatrix,ImageData,Path2D});
const dom = new JSDOM(''), X = spreadsheetLibrary();
const read = file => readTenderDocument(file,{loadXlsx:async()=>X,DOMParser:dom.window.DOMParser});
try {
  const files = await fixtures();
  const pdf = await read(files.pdf);
  assert.equal(pdf.analysis.state,'read'); assert.equal(pdf.kind,'booklet');
  assert.equal(pdf.analysis.schedule.due[0].date,'2026-12-04');
  assert.equal(pdf.analysis.highlights.find(x=>x.topic==='visit').locator,'1');
  const sheet = await read(files.sheet);
  assert.equal(sheet.kind,'boq'); assert.equal(sheet.analysis.tables[0].rows[1][2],'30');
  assert.equal(sheet.analysis.schedule.due[0].locator,'Schedule');
  const word = await read(files.word);
  assert.equal(word.analysis.state,'read'); assert.equal(word.analysis.schedule.due[0].date,'2026-12-06');
  assert.ok(word.analysis.highlights.some(x=>x.topic==='visit'));
  const csv = await read(new File(['Item,Description,Quantity\n1,Camera,30'],'items.csv'));
  assert.equal(csv.kind,'boq'); assert.equal(csv.analysis.tables[0].rows[1][2],'30');
  const long = X.utils.book_new(); X.utils.book_append_sheet(long,X.utils.aoa_to_sheet(Array.from({length:450},(_,i)=>[i,'Camera',1])),'Long');
  assert.equal((await read(new File([X.write(long,{type:'array',bookType:'xlsx'})],'long.xlsx'))).analysis.state,'partial');
  const blank = await PDFDocument.create(), scan=createCanvas(400,80);scan.getContext('2d').fillText('Scanned terms',20,30);
  const image=await blank.embedPng(scan.toBuffer('image/png'));blank.addPage().drawImage(image,{x:20,y:500,width:400,height:80});
  assert.equal((await read(new File([await blank.save()],'image-only.pdf'))).analysis.state,'empty');
  const mixed=await PDFDocument.load(await files.pdf.arrayBuffer());const mixedImage=await mixed.embedPng(scan.toBuffer('image/png'));mixed.addPage().drawImage(mixedImage,{x:20,y:500,width:400,height:80});
  assert.equal((await read(new File([await mixed.save()],'mixed.pdf'))).analysis.state,'partial','image-only pages must not silently disappear in a mixed PDF');
  assert.equal((await read(new File(['corrupt'],'broken.pdf'))).analysis.state,'error');
  assert.equal((await read(new File([readFileSync(new URL('fixtures/sample-protected.pdf',import.meta.url))],'protected.pdf'))).analysis.state,'locked');
  assert.equal((await read(new File(['<svg/>'],'logo.svg'))).analysis.state,'unsupported');
  assert.equal((await read({name:'big.pdf',size:26*1024*1024})).analysis.state,'large');
  const expanded = zipSync({'xl/sharedStrings.xml':strToU8('x'.repeat(26*1024*1024))});
  assert.equal((await read(new File([expanded],'expanded.xlsx'))).analysis.state,'large');
  const docxml = zipSync({'word/document.xml':strToU8('x'.repeat(9*1024*1024))});
  assert.equal((await read(new File([docxml],'expanded.docx'))).analysis.state,'large');
  const hostile = await read(new File(['Scope of work: <img src=x onerror=alert(1)>'],'text.txt'));
  assert.equal(hostile.analysis.highlights[0].text,'Scope of work: <img src=x onerror=alert(1)>');
  console.log('tender-documents: passed PDF, XLSX, Arabic DOCX, CSV, table limits, image-only, corrupt, unsupported, input/expansion limits and literal text evidence');
} finally { dom.window.close(); }
